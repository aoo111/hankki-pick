import streamlit as st
from openai import OpenAI
from pathlib import Path
import tempfile
import os


# =========================================================
# 1. 페이지 설정
# =========================================================

st.set_page_config(
    page_title="오늘 뭐 먹지?",
    page_icon="🍽️",
    layout="centered"
)

st.title("🍽️ 오늘 뭐 먹지?")

st.write(
    """
    오늘 어떤 음식을 먹을지 고민된다면 말씀해주세요! 😋

    취향과 상황을 분석해서 오늘 먹기 좋은 메뉴를 추천해드립니다.

    ⌨️ **글로 질문하거나**
    
    🎤 **직접 말해서 질문할 수도 있어요.**
    """
)


# =========================================================
# 2. OpenAI API KEY 설정
# =========================================================

try:
    openai_api_key = st.secrets["OPENAI_API_KEY"]

except Exception:

    openai_api_key = st.sidebar.text_input(
        "OpenAI API Key",
        type="password"
    )


if not openai_api_key:

    st.info(
        "왼쪽 메뉴에서 OpenAI API Key를 입력해주세요. 🔑"
    )

    st.stop()


client = OpenAI(
    api_key=openai_api_key
)


# =========================================================
# 3. 사용할 AI 모델
# =========================================================

TEXT_MODEL = "gpt-5.6"

TRANSCRIBE_MODEL = "gpt-transcribe"

VOICE_MODEL = "gpt-4o-mini-tts"


# =========================================================
# 4. 메뉴 추천 AI 역할 설정
# =========================================================

FOOD_SYSTEM_PROMPT = """
당신은 사용자가 오늘 먹을 음식을 결정하도록 도와주는
친근하고 센스 있는 AI 메뉴 추천 전문가입니다.

사용자의 상황, 음식 취향, 예산, 매운맛 선호도,
배고픔 정도와 현재 기분 등을 종합해서
오늘 가장 잘 어울리는 메뉴를 추천해야 합니다.


[당신의 역할]

사용자가

"오늘 뭐 먹지?"
"저녁 추천해줘"
"매콤한 거 먹고 싶어"
"만원 이하로 먹고 싶어"
"데이트 메뉴 추천해줘"

등의 질문을 하면 사용자의 상황을 분석해서
구체적인 메뉴를 추천하세요.


[메뉴 추천 시 고려할 정보]

1. 식사 시간
2. 음식 종류
3. 현재 기분
4. 매운 음식 선호도
5. 예산
6. 혼밥인지 여러 명인지
7. 배달인지 외식인지
8. 든든하게 먹고 싶은지
9. 먹기 싫은 음식
10. 먹지 못하는 음식
11. 이전에 이미 먹었다고 말한 음식


[추천 방식]

가능하면 메뉴를 3개 추천하세요.

다음 형태로 답변하세요.


### 🥇 오늘의 1순위
메뉴 이름

왜 지금 이 메뉴가 좋은지 짧게 설명하세요.


### 🥈 2순위
메뉴 이름

간단한 추천 이유를 설명하세요.


### 🥉 3순위
메뉴 이름

간단한 추천 이유를 설명하세요.


마지막에는 반드시

**🍽️ 오늘 하나만 고른다면: 메뉴 이름**

형태로 최종 메뉴 하나를 골라주세요.


[중요한 규칙]

- 메뉴를 너무 많이 나열하지 마세요.
- 최종적으로 하나를 확실하게 골라주세요.
- 사용자가 싫다고 말한 음식은 추천하지 마세요.
- 사용자가 이미 먹었다고 말한 음식도 가급적 제외하세요.
- 알레르기나 먹지 못하는 음식이 있다면 반드시 제외하세요.
- 사용자의 조건이 충분하면 불필요한 질문을 하지 마세요.
- 조건이 너무 부족할 때만 간단한 질문 1~2개를 하세요.
- 실제 존재 여부를 모르는 음식점 이름을 만들어내지 마세요.
- 확인하지 않은 날씨나 위치 정보를 만들어내지 마세요.
- 설명은 너무 길지 않게 해주세요.
- 친근하고 자연스러운 한국어로 이야기하세요.
- 메뉴를 결정해주는 것이 목적이므로 우유부단하게 답하지 마세요.
"""


# =========================================================
# 5. 처음 대화 설정
# =========================================================

WELCOME_MESSAGE = """
안녕하세요! 🍽️

오늘도 **뭐 먹을지 고민 중이신가요?**

제가 오늘 먹기 좋은 메뉴를 골라드릴게요. 😋

왼쪽에서 음식 취향을 선택해도 되고,
그냥 편하게 말씀하셔도 됩니다.

예를 들면,

- **오늘 저녁 뭐 먹지?**
- **매콤하고 든든한 거 먹고 싶어**
- **만원 정도로 혼밥 추천해줘**
- **데이트할 건데 메뉴 추천해줘**
- **어제 치킨 먹었으니까 치킨은 빼줘**

처럼 질문해보세요.

🎤 아래 마이크를 이용해 직접 말할 수도 있습니다!
"""


if "messages" not in st.session_state:

    st.session_state.messages = [
        {
            "role": "assistant",
            "content": WELCOME_MESSAGE,
            "voice": False
        }
    ]


# =========================================================
# 6. 사이드바 - 음식 취향 설정
# =========================================================

with st.sidebar:

    st.header("🍴 오늘의 식사 설정")

    st.caption(
        "모두 선택하지 않아도 괜찮아요."
    )


    # -----------------------------------------------------
    # 식사 시간
    # -----------------------------------------------------

    meal_time = st.selectbox(
        "🕐 언제 먹나요?",
        [
            "상관없음",
            "아침",
            "점심",
            "저녁",
            "야식"
        ]
    )


    # -----------------------------------------------------
    # 음식 종류
    # -----------------------------------------------------

    food_type = st.selectbox(
        "🍚 어떤 종류가 당기나요?",
        [
            "상관없음",
            "한식",
            "중식",
            "일식",
            "양식",
            "분식",
            "아시아 음식",
            "패스트푸드",
            "샐러드 / 건강식"
        ]
    )


    # -----------------------------------------------------
    # 누구와 먹는지
    # -----------------------------------------------------

    situation = st.selectbox(
        "👥 누구와 먹나요?",
        [
            "상관없음",
            "혼밥",
            "친구",
            "연인 / 데이트",
            "가족",
            "직장 동료"
        ]
    )


    # -----------------------------------------------------
    # 식사 방식
    # -----------------------------------------------------

    eating_method = st.selectbox(
        "🏠 어떻게 먹을까요?",
        [
            "상관없음",
            "외식",
            "배달",
            "포장",
            "집에서 만들어 먹기"
        ]
    )


    # -----------------------------------------------------
    # 예산
    # -----------------------------------------------------

    budget = st.selectbox(
        "💰 1인당 예산은?",
        [
            "상관없음",
            "5,000원 이하",
            "5,000원 ~ 10,000원",
            "10,000원 ~ 15,000원",
            "15,000원 ~ 30,000원",
            "30,000원 이상"
        ]
    )


    # -----------------------------------------------------
    # 매운맛
    # -----------------------------------------------------

    spicy = st.select_slider(
        "🌶️ 매운맛",
        options=[
            "안 매운 음식",
            "살짝 매콤",
            "적당히 매운맛",
            "아주 매운맛",
            "상관없음"
        ],
        value="상관없음"
    )


    # -----------------------------------------------------
    # 배고픔
    # -----------------------------------------------------

    hunger = st.select_slider(
        "🍖 지금 얼마나 배고픈가요?",
        options=[
            "가볍게",
            "보통",
            "든든하게",
            "엄청 배고픔"
        ],
        value="보통"
    )


    # -----------------------------------------------------
    # 현재 기분
    # -----------------------------------------------------

    mood = st.selectbox(
        "😊 지금 기분은?",
        [
            "상관없음",
            "기분 좋은 날",
            "스트레스 받음",
            "피곤함",
            "기분이 가라앉음",
            "뭔가 특별한 걸 먹고 싶음",
            "그냥 빨리 먹고 싶음"
        ]
    )


    # -----------------------------------------------------
    # 제외 음식
    # -----------------------------------------------------

    avoid_food = st.text_input(
        "🚫 먹기 싫거나 못 먹는 음식",
        placeholder="예: 해산물, 오이, 치즈"
    )


    st.divider()


    # -----------------------------------------------------
    # 음성 답변 설정
    # -----------------------------------------------------

    st.subheader("🔊 음성 설정")

    voice_answer = st.toggle(
        "음성 질문에 음성으로 답하기",
        value=True
    )

    st.caption(
        "음성 답변은 AI가 생성한 음성입니다."
    )


    st.divider()


    # -----------------------------------------------------
    # 대화 초기화
    # -----------------------------------------------------

    if st.button(
        "🗑️ 대화 초기화",
        use_container_width=True
    ):

        st.session_state.messages = [
            {
                "role": "assistant",
                "content": WELCOME_MESSAGE,
                "voice": False
            }
        ]

        st.rerun()


# =========================================================
# 7. 현재 선택 조건
# =========================================================

with st.expander(
    "🍴 현재 선택한 음식 조건 보기"
):

    st.write(
        f"**식사 시간:** {meal_time}"
    )

    st.write(
        f"**음식 종류:** {food_type}"
    )

    st.write(
        f"**식사 상대:** {situation}"
    )

    st.write(
        f"**식사 방법:** {eating_method}"
    )

    st.write(
        f"**예산:** {budget}"
    )

    st.write(
        f"**매운맛:** {spicy}"
    )

    st.write(
        f"**배고픔:** {hunger}"
    )

    st.write(
        f"**현재 기분:** {mood}"
    )

    if avoid_food:

        st.write(
            f"**제외 음식:** {avoid_food}"
        )

    else:

        st.write(
            "**제외 음식:** 없음"
        )


# =========================================================
# 8. 기존 대화 화면에 출력
# =========================================================

for message in st.session_state.messages:

    with st.chat_message(
        message["role"]
    ):

        # 음성으로 질문한 경우
        if (
            message["role"] == "user"
            and message.get("voice", False)
        ):

            st.markdown(
                "🎤 **음성으로 질문했습니다**"
            )


        st.markdown(
            message["content"]
        )


        # 과거 음성 답변이 있다면 재생
        if message.get("audio"):

            st.audio(
                message["audio"],
                format="audio/mp3"
            )


# =========================================================
# 9. 음성 입력
# =========================================================

st.divider()

st.subheader(
    "🎤 말해서 메뉴 추천받기"
)

st.caption(
    "마이크 버튼을 누르고 먹고 싶은 음식이나 상황을 말해주세요."
)


voice_audio = st.audio_input(
    "음성 녹음",
    sample_rate=16000
)


voice_send = st.button(
    "🎤 음성 질문 보내기",
    use_container_width=True,
    disabled=voice_audio is None
)


# =========================================================
# 10. 글 입력
# =========================================================

typed_prompt = st.chat_input(
    "오늘 뭐 먹을지 말씀해주세요 😋"
)


# =========================================================
# 11. 최종 질문 결정
# =========================================================

prompt = None

voice_mode = False


# ---------------------------------------------------------
# 음성 질문
# ---------------------------------------------------------

if voice_send and voice_audio is not None:

    try:

        with st.spinner(
            "🎧 음성을 글자로 바꾸고 있어요..."
        ):

            transcription = (
                client.audio.transcriptions.create(
                    model=TRANSCRIBE_MODEL,
                    file=voice_audio
                )
            )


            prompt = transcription.text.strip()

            voice_mode = True


        if not prompt:

            st.warning(
                "음성을 정확하게 인식하지 못했어요. 다시 말해주세요."
            )

            prompt = None


    except Exception as e:

        st.error(
            f"음성 인식 중 오류가 발생했습니다: {e}"
        )

        prompt = None


# ---------------------------------------------------------
# 글 질문
# ---------------------------------------------------------

elif typed_prompt:

    prompt = typed_prompt.strip()

    voice_mode = False


# =========================================================
# 12. 질문이 들어왔다면 처리
# =========================================================

if prompt:

    # -----------------------------------------------------
    # 사용자 질문 저장
    # -----------------------------------------------------

    st.session_state.messages.append(
        {
            "role": "user",
            "content": prompt,
            "voice": voice_mode
        }
    )


    # -----------------------------------------------------
    # 사용자 질문 출력
    # -----------------------------------------------------

    with st.chat_message("user"):

        if voice_mode:

            st.markdown(
                "🎤 **음성으로 질문했습니다**"
            )


        st.markdown(prompt)


    # =====================================================
    # 13. 현재 메뉴 조건을 AI에게 전달
    # =====================================================

    FOOD_CONTEXT = f"""
현재 사용자가 선택한 메뉴 추천 조건입니다.

식사 시간:
{meal_time}

선호 음식 종류:
{food_type}

누구와 먹는지:
{situation}

식사 방식:
{eating_method}

1인당 예상 예산:
{budget}

매운맛 선호:
{spicy}

배고픔 정도:
{hunger}

현재 기분:
{mood}

먹기 싫거나 먹지 못하는 음식:
{avoid_food if avoid_food else "특별히 없음"}


위의 선택 조건과 사용자가 대화에서 직접 이야기한
내용을 모두 고려해서 메뉴를 추천하세요.

사용자가 대화에서 직접 이야기한 내용과
위 선택 정보가 충돌하면 사용자가 직접 말한 내용을
우선적으로 따르세요.
"""


    # =====================================================
    # 14. OpenAI에 전달할 대화 기록
    # =====================================================

    conversation = []


    for message in st.session_state.messages:

        if message["role"] in [
            "user",
            "assistant"
        ]:

            conversation.append(
                {
                    "role": message["role"],
                    "content": message["content"]
                }
            )


    # =====================================================
    # 15. AI 메뉴 추천
    # =====================================================

    with st.chat_message("assistant"):

        try:

            with st.spinner(
                "🍳 오늘 먹기 좋은 메뉴를 고르고 있어요..."
            ):

                response = client.responses.create(

                    model=TEXT_MODEL,

                    instructions=(
                        FOOD_SYSTEM_PROMPT
                        + "\n\n"
                        + FOOD_CONTEXT
                    ),

                    input=conversation
                )


                assistant_response = (
                    response.output_text.strip()
                )


            # -------------------------------------------------
            # 글 답변 출력
            # -------------------------------------------------

            st.markdown(
                assistant_response
            )


            # =================================================
            # 16. 음성 질문이면 음성 답변 만들기
            # =================================================

            audio_bytes = None


            if voice_mode and voice_answer:

                try:

                    with st.spinner(
                        "🔊 음성 답변을 만들고 있어요..."
                    ):

                        # 임시 mp3 파일 생성
                        with tempfile.NamedTemporaryFile(
                            delete=False,
                            suffix=".mp3"
                        ) as temp_file:

                            speech_file_path = Path(
                                temp_file.name
                            )


                        # AI 음성 생성
                        with (
                            client.audio.speech
                            .with_streaming_response
                            .create(

                                model=VOICE_MODEL,

                                voice="coral",

                                input=assistant_response,

                                instructions=(
                                    "한국어로 자연스럽고 밝게 말하세요. "
                                    "오늘 먹을 메뉴를 추천해주는 "
                                    "친근한 친구처럼 이야기하세요. "
                                    "너무 과장되거나 빠르게 말하지 마세요."
                                )

                            )
                        ) as speech_response:

                            speech_response.stream_to_file(
                                speech_file_path
                            )


                        # 파일을 읽어서 Streamlit에 전달
                        audio_bytes = (
                            speech_file_path.read_bytes()
                        )


                        # 임시 파일 삭제
                        try:

                            os.remove(
                                speech_file_path
                            )

                        except Exception:

                            pass


                    # -------------------------------------------------
                    # 음성 자동 재생
                    # -------------------------------------------------

                    st.caption(
                        "🔊 아래 음성은 AI가 생성한 음성입니다."
                    )

                    st.audio(
                        audio_bytes,
                        format="audio/mp3",
                        autoplay=True
                    )


                except Exception as e:

                    st.warning(
                        f"음성 답변 생성 중 오류가 발생했습니다: {e}"
                    )


            # =================================================
            # 17. AI 답변 저장
            # =================================================

            assistant_message = {

                "role": "assistant",

                "content": assistant_response,

                "voice": (
                    voice_mode
                    and voice_answer
                )
            }


            # 음성 파일도 대화 기록에 저장
            if audio_bytes:

                assistant_message[
                    "audio"
                ] = audio_bytes


            st.session_state.messages.append(
                assistant_message
            )


        except Exception as e:

            st.error(
                f"AI 답변 생성 중 오류가 발생했습니다: {e}"
            )
